export function contentSecurityPolicy(nonce?: string, development = false): string {
  const connect = ["'self'", "https://nominatim.openstreetmap.org"];
  try {
    const url = new URL(process.env.NEXT_PUBLIC_SUPABASE_URL ?? "");
    if (url.protocol === "https:" || development && url.protocol === "http:" && ["localhost", "127.0.0.1"].includes(url.hostname)) {
      connect.push(url.origin, `${url.protocol === "https:" ? "wss:" : "ws:"}//${url.host}`);
    }
  } catch { /* Unconfigured access fails closed independently. */ }
  if (development) connect.push("ws://localhost:*", "ws://127.0.0.1:*", "http://localhost:*", "http://127.0.0.1:*");
  const scripts = development ? "'self' 'unsafe-inline' 'unsafe-eval'" : `'self'${nonce ? ` 'nonce-${nonce}'` : ""}`;
  return `default-src 'self'; script-src ${scripts}; script-src-attr 'none'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob: https://tile.openstreetmap.org; font-src 'self' data:; connect-src ${connect.join(" ")}; frame-src 'self' data: blob:; media-src 'self' data: blob:; worker-src 'self' blob:; form-action 'self'; base-uri 'self'; object-src 'none'; frame-ancestors 'self'`;
}
export const securityHeaders: Record<string,string> = {
  "X-Content-Type-Options": "nosniff",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  "X-Frame-Options": "SAMEORIGIN",
  "Content-Security-Policy": contentSecurityPolicy(undefined, process.env.NODE_ENV === "development"),
  "Permissions-Policy": "camera=(self), microphone=(self), geolocation=(self)",
};
export function secureResponse(response: Response, request: Request) {
  const headers = new Headers(response.headers);
  for (const [name,value] of Object.entries(securityHeaders)) {
    // Preserve the per-response nonce generated by our middleware, not caller input.
    if (name === "Content-Security-Policy" && headers.has(name)) continue;
    headers.set(name,value);
  }
  if (new URL(request.url).protocol === "https:") headers.set("Strict-Transport-Security","max-age=31536000; includeSubDomains");
  return new Response(response.body,{ status: response.status, statusText: response.statusText, headers });
}
